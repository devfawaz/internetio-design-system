// Builds dist/ from tokens/*.json (DTCG-style: $value, $type, {alias.paths}).
//   dist/tokens.css          CSS custom properties; semantic tokens keep var() references so changing a
//                            primitive at runtime changes everything that uses it
//   dist/tailwind-theme.css  the same tokens inside a Tailwind v4 @theme block (optional consumer)
//   dist/tokens.json         flat, fully resolved values with status metadata
//   dist/TOKENS.md           reference table and provenance counts
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokDir = join(root, "tokens");
const dist = join(root, "dist");
mkdirSync(dist, { recursive: true });

// ── load and flatten ─────────────────────────────────────────
const flat = new Map(); // path -> { path, value, type, description, status, meta }
function walk(node, path, inheritedType, groupDesc) {
  const type = node.$type ?? inheritedType;
  if ("$value" in node) {
    const iio = node.$extensions?.iio ?? {};
    flat.set(path.join("."), {
      path: path.join("."), value: node.$value, type: node.$type ?? inheritedType,
      description: node.$description ?? groupDesc ?? "", status: iio.status ?? "derived", meta: iio,
    });
    return;
  }
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$") || typeof v !== "object" || v === null) continue;
    walk(v, [...path, k], type, node.$description ?? undefined);
  }
}
for (const file of readdirSync(tokDir).filter((f) => f.endsWith(".json")).sort()) {
  const json = JSON.parse(readFileSync(join(tokDir, file), "utf8"));
  for (const [k, v] of Object.entries(json)) {
    if (k.startsWith("$") || typeof v !== "object") continue;
    walk(v, [k], undefined);
  }
}

// ── names ────────────────────────────────────────────────────
// Tailwind v4 theme namespaces where they exist, so tokens.css doubles as a Tailwind theme.
function cssName(path) {
  const p = path.split(".");
  const [a, b, ...rest] = p;
  const join = (...xs) => "--" + xs.join("-");
  if (a === "size" && b === "font") return join("text", ...rest);
  if (a === "size" && b === "space") return join("space", ...rest);
  if (a === "size" && b === "control") return join("size-control", ...rest);
  if (a === "font" && b === "family") return join("font", ...rest);
  if (a === "font" && b === "weight") return join("font-weight", ...rest);
  if (a === "text") return join("type", b, ...rest);
  return join(...p);
}
const refToVar = (ref) => `var(${cssName(ref)})`;
const isAlias = (v) => typeof v === "string" && /^\{[^}]+\}$/.test(v);
const aliasPath = (v) => v.slice(1, -1);

function resolve(v, seen = new Set()) {
  if (typeof v === "string" && v.includes("{")) {
    return v.replace(/\{([^}]+)\}/g, (_, p) => {
      const t = flat.get(p);
      if (!t) throw new Error(`Unresolved alias {${p}}`);
      if (seen.has(p)) throw new Error(`Circular alias {${p}}`);
      return String(resolve(t.value, new Set([...seen, p])));
    });
  }
  return v;
}
const cssValue = (v) => (typeof v === "string" ? v.replace(/\{([^}]+)\}/g, (_, p) => refToVar(p)) : String(v));

// validate every alias resolves
for (const t of flat.values()) resolve(t.value);

// ── tokens.css ───────────────────────────────────────────────
const groups = [
  ["Colour: primitives", (t) => t.path.startsWith("color.") && !/^color\.(text|surface|border|action|feedback|effect|m3)\./.test(t.path)],
  ["Colour: semantic", (t) => /^color\.(text|surface|border|action|feedback|effect)\./.test(t.path)],
  ["Colour: Material 3 (Android layer)", (t) => t.path.startsWith("color.m3.")],
  ["Type: families, weights, sizes", (t) => /^(font|size\.font)/.test(t.path)],
  ["Type: text styles", (t) => t.path.startsWith("text.")],
  ["Space and control sizes", (t) => /^size\.(space|control)/.test(t.path)],
  ["Radius", (t) => t.path.startsWith("radius.")],
  ["Elevation and focus", (t) => /^(shadow|focus|state)\./.test(t.path)],
  ["Motion", (t) => /^(duration|ease|motion)\./.test(t.path)],
  ["Layering and breakpoints", (t) => /^(z|breakpoint)\./.test(t.path)],
  ["Components", (t) => /^(button|icon-button|searchbar|card|chip|sheet|avatar)\./.test(t.path)],
];
const used = new Set();
let css = "/* internet.io design tokens. Generated by scripts/build.mjs from tokens/*.json. Do not edit by hand. */\n:root {\n";
for (const [title, test] of groups) {
  const rows = [...flat.values()].filter((t) => test(t) && !used.has(t.path));
  if (!rows.length) continue;
  css += `\n  /* ${title} */\n`;
  for (const t of rows) {
    used.add(t.path);
    css += `  ${cssName(t.path)}: ${cssValue(t.value)};\n`;
  }
}
// Tailwind-style line-height companions for the size scale, derived from the text styles that use each size
css += "}\n";
const leftover = [...flat.values()].filter((t) => !used.has(t.path));
if (leftover.length) throw new Error("Tokens not assigned to a CSS group: " + leftover.map((t) => t.path).join(", "));
writeFileSync(join(dist, "tokens.css"), css);

// ── tailwind-theme.css ───────────────────────────────────────
let tw = "/* internet.io tokens as a Tailwind v4 theme. Generated. Use: @import \"tailwindcss\"; @import \"./tailwind-theme.css\"; */\n@theme {\n";
const twKeep = [...flat.values()].filter((t) => /^(color\.|radius\.|shadow\.|font\.|ease\.|size\.font\.|breakpoint\.)/.test(t.path) && t.type !== "shadow" || t.path.startsWith("shadow."));
for (const t of twKeep) {
  const name = t.path.startsWith("breakpoint.") ? cssName(t.path) : cssName(t.path);
  tw += `  ${name}: ${cssValue(t.value)};\n`;
}
tw += "}\n";
writeFileSync(join(dist, "tailwind-theme.css"), tw);

// ── tokens.json ──────────────────────────────────────────────
const out = {};
for (const t of flat.values()) {
  out[t.path] = {
    value: resolve(t.value), alias: isAlias(t.value) ? aliasPath(t.value) : undefined, type: t.type, css: cssName(t.path), status: t.status,
    ...(t.description && { description: t.description }),
    ...(t.meta.audit && { audit: t.meta.audit }), ...(t.meta.consolidates && { consolidates: t.meta.consolidates }), ...(t.meta.note && { note: t.meta.note }), ...(t.meta.figma && { figma: t.meta.figma }),
  };
}
writeFileSync(join(dist, "tokens.json"), JSON.stringify(out, null, 2) + "\n");
// The docs page reads this file so it also works when opened straight from disk.
mkdirSync(join(root, "docs"), { recursive: true });
writeFileSync(join(root, "docs", "tokens.data.js"), "// Generated by scripts/build.mjs. Do not edit.\nwindow.TOKENS = " + JSON.stringify(out) + ";\n");

// ── TOKENS.md ────────────────────────────────────────────────
const counts = { figma: 0, proposed: 0, derived: 0 };
for (const t of flat.values()) counts[t.status] = (counts[t.status] ?? 0) + 1;
let md = `# Token reference\n\nGenerated from \`tokens/*.json\`. ${flat.size} tokens: ${counts.figma} defined in Figma, ${counts.proposed} proposed from the code audit, ${counts.derived} derived (semantic and component aliases).\n\n`;
for (const [title] of groups) {
  const rows = [...flat.values()].filter((t) => groups.find((g) => g[0] === title)[1](t));
  md += `## ${title}\n\n| Token | CSS variable | Value | Source |\n|---|---|---|---|\n`;
  for (const t of rows) md += `| \`${t.path}\` | \`${cssName(t.path)}\` | \`${String(resolve(t.value)).replace(/\|/g, "\\|")}\` | ${t.status} |\n`;
  md += "\n";
}
writeFileSync(join(dist, "TOKENS.md"), md);

console.log(`Built ${flat.size} tokens: figma ${counts.figma}, proposed ${counts.proposed}, derived ${counts.derived}`);
